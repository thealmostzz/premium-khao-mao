function getTextTranslation(lang, key) {
  return textTranslations[lang]?.[key] ?? textTranslations.th[key] ?? "";
}

function getHtmlTranslation(lang, key) {
  return htmlTranslations[lang]?.[key] ?? htmlTranslations.th[key] ?? "";
}

function applyTextTranslations(lang) {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = getTextTranslation(lang, key);
    if (value) {
      el.textContent = value;
    }
  });
}

function applyHtmlTranslations(lang) {
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    const value = getHtmlTranslation(lang, key);
    if (value) {
      el.innerHTML = value;
    }
  });
}

function applyAttributeTranslations(lang) {
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const mappings = el.getAttribute("data-i18n-attr").split(",");
    mappings.forEach((mapping) => {
      const [attrName, key] = mapping.split(":").map((value) => value.trim());
      const translatedValue = getTextTranslation(lang, key);
      if (attrName && translatedValue) {
        el.setAttribute(attrName, translatedValue);
      }
    });
  });
}

function applyMetaTranslations(lang) {
  const meta = metaTranslations[lang] ?? metaTranslations.th;
  document.title = meta.title;

  const setContent = (id, value) => {
    const el = document.getElementById(id);
    if (el) {
      el.setAttribute("content", value);
    }
  };

  setContent("meta-description", meta.description);
  setContent("meta-keywords", meta.keywords);
  setContent("meta-twitter-title", meta.twitterTitle);
  setContent("meta-twitter-description", meta.twitterDescription);
  setContent("meta-og-title", meta.ogTitle);
  setContent("meta-og-description", meta.ogDescription);

  const structuredDataScript = document.getElementById("structured-data");
  if (structuredDataScript) {
    structuredDataScript.textContent = JSON.stringify(meta.structuredData);
  }
}

function updateLanguageToggleState(lang) {
  document.querySelectorAll(".lang-toggle").forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function setLanguage(lang) {
  const resolvedLang = textTranslations[lang] ? lang : "th";
  localStorage.setItem("preferredLanguage", resolvedLang);
  document.documentElement.lang = resolvedLang;

  updateLanguageToggleState(resolvedLang);
  applyTextTranslations(resolvedLang);
  applyHtmlTranslations(resolvedLang);
  applyAttributeTranslations(resolvedLang);
  applyMetaTranslations(resolvedLang);

  window.dispatchEvent(new CustomEvent("languagechange", { detail: { lang: resolvedLang } }));
}

function getCurrentLanguage() {
  const savedLang = localStorage.getItem("preferredLanguage");
  return textTranslations[savedLang] ? savedLang : "th";
}

window.setLanguage = setLanguage;
window.getCurrentLanguage = getCurrentLanguage;

document.addEventListener("DOMContentLoaded", () => {
  setLanguage(getCurrentLanguage());
});
