// Language logic
function setLanguage(lang) {
  localStorage.setItem('preferredLanguage', lang);
  document.documentElement.lang = lang;
  
  // Update toggle buttons UI
  document.querySelectorAll('.lang-toggle').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.add('font-bold', 'text-leaf', 'opacity-100');
      btn.classList.remove('text-riceBrown', 'font-medium', 'opacity-60');
    } else {
      btn.classList.remove('font-bold', 'text-leaf', 'opacity-100');
      btn.classList.add('text-riceBrown', 'font-medium', 'opacity-60');
    }
  });

  // Apply translations
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });
}

// Initialize on load
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('preferredLanguage') || 'th';
  setLanguage(savedLang);
});
